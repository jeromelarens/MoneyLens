import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { MemoryRouter, Routes, Route } from 'react-router-dom';
import { ActionDetailsPage } from '../components/ActionDetailsPage';
import { financialService } from '../services/financial.service';
import type {
  BusinessAction,
  ActionHistory,
  FinancialFinding,
  Transaction,
} from '@moneylens/shared';

describe('ActionDetailsPage Component Suite (Page 15)', () => {
  let queryClient: QueryClient;

  const mockAction: BusinessAction = {
    id: 'act-corp-900',
    organizationId: 'org-test-workspace',
    actionType: 'review_duplicate_payment',
    category: 'cost_reduction',
    title: 'Review Suspected Duplicate Charge: Supplier ABC ($150.00)',
    explanation:
      'Multiple debit transactions posted within 24 hours share identical amounts and reference tokens.',
    priority: 'high',
    priorityScore: 78,
    severity: 'high',
    status: 'open',
    evidence: {
      primaryAmountMinor: 15000,
      ruleId: 'RULE_ACT_DUP_001',
      dateDifferenceHours: 18,
    },
    sourceFindingIds: ['find-dup-900'],
    sourceForecastRunId: 'fc-run-500',
    currency: 'USD',
    financialImpact: {
      currency: 'USD',
      potentialExposureMinor: 15000,
      estimatedAvoidableCostMinor: 15000,
      confirmedIssueMinor: 0,
      projectedCashFlowEffectMinor: 0,
      realizedSavingsMinor: 0,
    },
    evidenceQuality: 'high',
    recommendedSteps: [
      {
        stepNumber: 1,
        label: 'Review Linked Transactions',
        description: 'Compare transaction timestamps and invoice tokens in statement ledger.',
        isOptional: false,
      },
      {
        stepNumber: 2,
        label: 'Verify Vendor Invoice',
        description: 'Confirm with counterparty whether distinct purchase orders exist.',
        isOptional: true,
      },
    ],
    ruleId: 'RULE_ACT_DUP_001',
    ruleVersion: 'v1.0.0',
    fingerprint: 'fp-dup-corp-900',
    snoozedUntil: null,
    completedAt: null,
    completionNotes: null,
    dismissedAt: null,
    dismissalReason: null,
    createdAt: '2026-10-20T10:00:00.000Z',
    updatedAt: '2026-10-20T10:00:00.000Z',
    lastEvaluatedAt: '2026-10-20T12:00:00.000Z',
  };

  const mockHistory: ActionHistory[] = [
    {
      id: 'hist-1',
      organizationId: 'org-test-workspace',
      actionId: 'act-corp-900',
      previousStatus: null,
      nextStatus: 'open',
      eventType: 'created',
      actorId: 'system',
      reason: 'Action generated by recommendation rule RULE_ACT_DUP_001',
      notes: null,
      metadata: { ruleVersion: 'v1.0.0' },
      createdAt: '2026-10-20T10:00:00.000Z',
    },
    {
      id: 'hist-2',
      organizationId: 'org-test-workspace',
      actionId: 'act-corp-900',
      previousStatus: 'open',
      nextStatus: 'in_progress',
      eventType: 'status_transition',
      actorId: 'org-test-workspace',
      reason: 'Began operational review with vendor',
      notes: null,
      metadata: null,
      createdAt: '2026-10-21T09:30:00.000Z',
    },
  ];

  const mockFinding: FinancialFinding = {
    id: 'find-dup-900',
    organizationId: 'org-test-workspace',
    findingType: 'potential_duplicate_payment',
    status: 'open',
    severity: 'high',
    title: 'Duplicate Outflow to Acme Cloud Corp ($150.00)',
    summary: 'Two duplicate debits identified.',
    primaryTransactionIds: ['tx-1'],
    relatedTransactionIds: ['tx-2'],
    evidence: {
      ruleId: 'RULE_DUP_001',
      ruleVersion: 'v1.0.0',
      reason: 'Matching amounts and tokens',
      primaryTransactionIds: ['tx-1'],
      relatedTransactionIds: ['tx-2'],
    },
    estimatedAmountMinor: 15000,
    currency: 'USD',
    ruleId: 'RULE_DUP_001',
    ruleVersion: 'v1.0.0',
    detectedAt: '2026-10-19T08:00:00.000Z',
    lastEvaluatedAt: '2026-10-20T12:00:00.000Z',
    fingerprint: 'fp-find-900',
    createdAt: '2026-10-19T08:00:00.000Z',
    updatedAt: '2026-10-19T08:00:00.000Z',
  };

  const mockTransactions: Transaction[] = [
    {
      id: 'tx-1',
      organizationId: 'org-test-workspace',
      accountId: 'acc-1',
      importJobId: 'job-1',
      date: '2026-10-18T10:00:00.000Z',
      description: 'ACME CLOUD CORP - SUBSCRIPTION',
      direction: 'debit',
      amountMinor: 15000,
      amountDecimal: '150.00',
      currency: 'USD',
      sourceReference: 'INV-901',
      fingerprint: 'fp-tx-1',
      createdAt: '2026-10-18T10:00:00.000Z',
      updatedAt: '2026-10-18T10:00:00.000Z',
    },
  ];

  beforeEach(() => {
    vi.restoreAllMocks();
    queryClient = new QueryClient({
      defaultOptions: {
        queries: { retry: false },
      },
    });

    vi.spyOn(financialService, 'getActionById').mockResolvedValue({
      data: mockAction,
    });

    vi.spyOn(financialService, 'getActionHistory').mockResolvedValue({
      data: mockHistory,
    });

    vi.spyOn(financialService, 'getFindingDetail').mockResolvedValue({
      finding: mockFinding,
      transactions: mockTransactions,
      history: [],
    });

    vi.spyOn(financialService, 'transitionAction').mockResolvedValue({
      data: { ...mockAction, status: 'in_progress' },
    });
  });

  const renderComponent = (actionId = 'act-corp-900') => {
    return render(
      <QueryClientProvider client={queryClient}>
        <MemoryRouter initialEntries={[`/actions/${actionId}`]}>
          <Routes>
            <Route path="/actions/:actionId" element={<ActionDetailsPage />} />
          </Routes>
        </MemoryRouter>
      </QueryClientProvider>,
    );
  };

  it('renders page header, brand identity, action title, and overview metadata', async () => {
    renderComponent();

    expect(
      await screen.findByRole('heading', {
        level: 1,
        name: /Review Suspected Duplicate Charge: Supplier ABC/i,
      }),
    ).toBeInTheDocument();
    expect(screen.getByText('MoneyLens')).toBeInTheDocument();
    expect(screen.getByText('OPEN')).toBeInTheDocument();
    expect(screen.getByText(/HIGH Priority \(78\/100\)/)).toBeInTheDocument();
    expect(screen.getAllByText('cost reduction').length).toBeGreaterThanOrEqual(1);
    expect(screen.getByText('HIGH Evidence Quality')).toBeInTheDocument();
    expect(screen.getByText('Duplicate Payment Review')).toBeInTheDocument();
  });

  it('displays granular financial impact breakdown without fabricating realized savings', async () => {
    renderComponent();

    expect(await screen.findByText('Granular Financial Exposure & Impact')).toBeInTheDocument();
    expect(screen.getByText('Potential Exposure')).toBeInTheDocument();
    expect(screen.getByText('Est. Avoidable Cost')).toBeInTheDocument();
    expect(screen.getByText('Realized Savings')).toBeInTheDocument();
    expect(screen.getAllByText(/\$ ?150\.00/).length).toBeGreaterThanOrEqual(1);
    expect(screen.getAllByText(/\$ ?0\.00/).length).toBeGreaterThanOrEqual(1);
    expect(screen.getByText(/Financial Truth Disclaimer/)).toBeInTheDocument();
  });

  it('renders recommended operational steps with step numbers and optional badges', async () => {
    renderComponent();

    expect(await screen.findByText('Recommended Operational Steps')).toBeInTheDocument();
    expect(screen.getByText('Review Linked Transactions')).toBeInTheDocument();
    expect(screen.getByText('Verify Vendor Invoice')).toBeInTheDocument();
    expect(screen.getByText('Optional')).toBeInTheDocument();
  });

  it('renders originating source evidence, linked finding, and linked forecast run', async () => {
    renderComponent();

    expect(await screen.findByText('Originating Source Evidence')).toBeInTheDocument();
    expect(await screen.findByText(/Duplicate Outflow to Acme Cloud Corp/i)).toBeInTheDocument();
    expect(screen.getByText('Linked Cash Flow Forecast')).toBeInTheDocument();
    expect(screen.getByText('Run ID: fc-run-500')).toBeInTheDocument();
    expect(screen.getByText('ACME CLOUD CORP - SUBSCRIPTION')).toBeInTheDocument();
  });

  it('renders chronological audit history timeline with actor and transition details', async () => {
    renderComponent();

    expect(await screen.findByText('Recorded Activity & Audit Trail')).toBeInTheDocument();
    expect(screen.getByText('2 Recorded Events')).toBeInTheDocument();
    expect(screen.getByText('created')).toBeInTheDocument();
    expect(screen.getByText('status transition')).toBeInTheDocument();
    expect(screen.getByText('Began operational review with vendor')).toBeInTheDocument();
  });

  it('accurately documents ownership at organization level and absence of individual assignment', async () => {
    renderComponent();

    expect(await screen.findByText('Accountability & Ownership')).toBeInTheDocument();
    expect(screen.getAllByText('Primary Retail Workspace').length).toBeGreaterThanOrEqual(1);
    expect(
      screen.getByText(
        /Organization-wide responsibility \(individual user assignments not modeled in current schema\)/,
      ),
    ).toBeInTheDocument();
  });

  it('handles Start Work lifecycle transition', async () => {
    renderComponent();

    const startWorkBtn = await screen.findByRole('button', { name: /Start Work/i });
    fireEvent.click(startWorkBtn);

    expect(screen.getByText('Start Working on Action')).toBeInTheDocument();

    const confirmBtn = screen.getByRole('button', { name: /Confirm Transition/i });
    fireEvent.click(confirmBtn);

    await waitFor(() => {
      expect(financialService.transitionAction).toHaveBeenCalledWith('act-corp-900', {
        status: 'in_progress',
        reason: undefined,
        notes: undefined,
      });
    });
  });

  it('requires a dismissal reason when dismissing an action', async () => {
    renderComponent();

    const dismissBtn = await screen.findByRole('button', { name: /Dismiss Action/i });
    fireEvent.click(dismissBtn);

    expect(screen.getByRole('heading', { level: 3, name: /Dismiss Action/i })).toBeInTheDocument();

    const confirmBtn = screen.getByRole('button', { name: /Confirm Transition/i });
    fireEvent.click(confirmBtn);

    expect(screen.getByText('A non-empty dismissal reason is required.')).toBeInTheDocument();
    expect(financialService.transitionAction).not.toHaveBeenCalled();

    const reasonInput = screen.getByLabelText(/Dismissal Reason/i);
    fireEvent.change(reasonInput, {
      target: { value: 'Authorized software subscription verified by store manager' },
    });
    fireEvent.click(confirmBtn);

    await waitFor(() => {
      expect(financialService.transitionAction).toHaveBeenCalledWith('act-corp-900', {
        status: 'dismissed',
        reason: 'Authorized software subscription verified by store manager',
        notes: undefined,
      });
    });
  });

  it('supports snooze with duration presets and passes snoozedUntil', async () => {
    renderComponent();

    const snoozeBtn = await screen.findByRole('button', { name: /Snooze Action/i });
    fireEvent.click(snoozeBtn);

    expect(screen.getByText('Select Snooze Duration')).toBeInTheDocument();

    const confirmBtn = screen.getByRole('button', { name: /Confirm Transition/i });
    fireEvent.click(confirmBtn);

    await waitFor(() => {
      expect(financialService.transitionAction).toHaveBeenCalled();
      const callArgs = vi.mocked(financialService.transitionAction).mock.calls[0]!;
      expect(callArgs[0]).toBe('act-corp-900');
      expect(callArgs[1].status).toBe('snoozed');
      expect(callArgs[1].snoozedUntil).toBeDefined();
    });
  });

  it('allows entering completion notes when marking an action completed', async () => {
    renderComponent();

    const completeBtn = await screen.findByRole('button', { name: /Mark Completed/i });
    fireEvent.click(completeBtn);

    expect(screen.getByText('Mark Action Completed')).toBeInTheDocument();

    const notesInput = screen.getByLabelText(/Completion Notes/i);
    fireEvent.change(notesInput, {
      target: { value: 'Vendor issued credit note CN-8821 for $150.00' },
    });

    const confirmBtn = screen.getByRole('button', { name: /Confirm Transition/i });
    fireEvent.click(confirmBtn);

    await waitFor(() => {
      expect(financialService.transitionAction).toHaveBeenCalledWith('act-corp-900', {
        status: 'completed',
        notes: 'Vendor issued credit note CN-8821 for $150.00',
        reason: undefined,
      });
    });
  });

  it('renders 404 state when action ID is not found', async () => {
    vi.spyOn(financialService, 'getActionById').mockRejectedValue(
      new Error('404: ACTION_NOT_FOUND'),
    );

    renderComponent('act-nonexistent');

    expect(
      await screen.findByRole('heading', { name: /Business Action Not Found/i }),
    ).toBeInTheDocument();
    expect(screen.getByRole('link', { name: /Return to Action Center/i })).toBeInTheDocument();
  });

  it('handles completed action state and presents completion notes and reopen control', async () => {
    vi.spyOn(financialService, 'getActionById').mockResolvedValue({
      data: {
        ...mockAction,
        status: 'completed',
        completedAt: '2026-10-22T14:00:00.000Z',
        completionNotes: 'Refund issued by vendor.',
      },
    });

    renderComponent();

    expect(await screen.findByText(/Action Completed at/)).toBeInTheDocument();
    expect(screen.getByText(/“Refund issued by vendor.”/)).toBeInTheDocument();
    expect(screen.getByRole('button', { name: /Reopen Action/i })).toBeInTheDocument();
  });

  it('handles snoozed action with active countdown', async () => {
    const futureDate = new Date(Date.now() + 5 * 86400000).toISOString();
    vi.spyOn(financialService, 'getActionById').mockResolvedValue({
      data: {
        ...mockAction,
        status: 'snoozed',
        snoozedUntil: futureDate,
      },
    });

    renderComponent();

    expect(await screen.findByText(/Snooze Deadline Active:/)).toBeInTheDocument();
    expect(screen.getAllByText(/Active \(due in 5 days\)/).length).toBeGreaterThanOrEqual(1);
    expect(screen.getByRole('button', { name: /Reopen Now/i })).toBeInTheDocument();
  });

  it('handles empty audit history gracefully without error', async () => {
    vi.spyOn(financialService, 'getActionHistory').mockResolvedValue({
      data: [],
    });

    renderComponent();

    expect(
      await screen.findByText('No historical lifecycle changes recorded yet for this action.'),
    ).toBeInTheDocument();
  });
});
