import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { ActionCenterDashboard } from '../components/ActionCenterDashboard';
import { financialService } from '../services/financial.service';
import type {
  BusinessAction,
  ActionDashboardSummary,
  ActionListResponse,
  ActionHistory,
} from '@moneylens/shared';

describe('ActionCenterDashboard Component Suite', () => {
  let queryClient: QueryClient;

  const mockSummary: ActionDashboardSummary = {
    totalOpen: 3,
    totalInProgress: 1,
    totalSnoozed: 1,
    totalCompleted: 2,
    totalDismissed: 1,
    criticalPriorityCount: 1,
    highPriorityCount: 2,
    mediumPriorityCount: 1,
    lowPriorityCount: 0,
    byCurrency: {
      USD: {
        currency: 'USD',
        potentialExposureMinor: 15000,
        estimatedAvoidableCostMinor: 15000,
        confirmedIssueMinor: 0,
        realizedSavingsMinor: 0,
        actionCount: 2,
      },
    },
    lastEvaluatedAt: '2026-10-20T12:00:00.000Z',
  };

  const mockAction: BusinessAction = {
    id: 'act-101',
    organizationId: 'org-test',
    actionType: 'review_duplicate_payment',
    category: 'cost_reduction',
    title: 'Review Suspected Duplicate Charge: Supplier ABC ($150.00)',
    explanation:
      'Multiple debit transactions posted within 24 hours share identical amounts and reference tokens.',
    priority: 'high',
    priorityScore: 75,
    severity: 'high',
    status: 'open',
    evidence: { primaryAmountMinor: 15000 },
    sourceFindingIds: ['find-dup-1'],
    sourceForecastRunId: null,
    currency: 'USD',
    financialImpact: {
      currency: 'USD',
      potentialExposureMinor: 15000,
      estimatedAvoidableCostMinor: 15000,
      confirmedIssueMinor: 0,
      projectedCashFlowEffectMinor: 0,
      realizedSavingsMinor: 0,
    },
    evidenceQuality: 'high',
    recommendedSteps: [
      {
        stepNumber: 1,
        label: 'Review Linked Transactions',
        description: 'Compare transaction timestamps and invoice tokens in statement ledger.',
        isOptional: false,
      },
      {
        stepNumber: 2,
        label: 'Verify Vendor Invoice',
        description: 'Confirm with counterparty whether distinct purchase orders exist.',
        isOptional: false,
      },
    ],
    ruleId: 'RULE_ACT_DUP_001',
    ruleVersion: 'v1.0.0',
    fingerprint: 'fp-dup-101',
    snoozedUntil: null,
    completedAt: null,
    completionNotes: null,
    dismissedAt: null,
    dismissalReason: null,
    createdAt: '2026-10-20T10:00:00.000Z',
    updatedAt: '2026-10-20T10:00:00.000Z',
    lastEvaluatedAt: '2026-10-20T12:00:00.000Z',
  };

  const mockListResponse: ActionListResponse = {
    items: [mockAction],
    pagination: {
      page: 1,
      limit: 15,
      totalItems: 1,
      totalPages: 1,
    },
  };

  const mockHistory: ActionHistory[] = [
    {
      id: 'hist-1',
      organizationId: 'org-test',
      actionId: 'act-101',
      previousStatus: null,
      nextStatus: 'open',
      eventType: 'created',
      actorId: 'system',
      reason: 'Action generated by recommendation rule RULE_ACT_DUP_001',
      notes: null,
      metadata: null,
      createdAt: '2026-10-20T10:00:00.000Z',
    },
  ];

  beforeEach(() => {
    vi.restoreAllMocks();
    queryClient = new QueryClient({
      defaultOptions: {
        queries: { retry: false },
      },
    });

    vi.spyOn(financialService, 'getActionSummary').mockResolvedValue({
      data: mockSummary,
    });

    vi.spyOn(financialService, 'getActions').mockResolvedValue(mockListResponse);

    vi.spyOn(financialService, 'getActionById').mockResolvedValue({
      data: mockAction,
    });

    vi.spyOn(financialService, 'getActionHistory').mockResolvedValue({
      data: mockHistory,
    });

    vi.spyOn(financialService, 'evaluateActions').mockResolvedValue({
      data: {
        totalEvaluated: 1,
        createdCount: 0,
        updatedCount: 1,
        supersededCount: 0,
        unchangedCount: 0,
        evaluatedAt: '2026-10-20T14:00:00.000Z',
      },
    });

    vi.spyOn(financialService, 'transitionAction').mockResolvedValue({
      data: { ...mockAction, status: 'in_progress' },
    });
  });

  const renderComponent = () => {
    return render(
      <QueryClientProvider client={queryClient}>
        <ActionCenterDashboard />
      </QueryClientProvider>,
    );
  };

  it('renders executive summary counts and segregated currency exposure', async () => {
    renderComponent();

    expect(await screen.findByText('Business Action Center')).toBeInTheDocument();
    // Critical & High card and Open Tasks card both display 3
    expect(screen.getByText('Critical & High')).toBeInTheDocument();
    const countElements = await screen.findAllByText('3');
    expect(countElements.length).toBeGreaterThanOrEqual(1);

    // Segregated Currency Exposure
    expect(await screen.findByText('USD Exposure')).toBeInTheDocument();
    expect(screen.getAllByText(/USD 150\.00/).length).toBeGreaterThanOrEqual(1);
  });

  it('renders action cards with priority score, recommended step, and title', async () => {
    renderComponent();

    expect(
      await screen.findByText(/Review Suspected Duplicate Charge: Supplier ABC/),
    ).toBeInTheDocument();

    expect(screen.getByText(/HIGH \(75 pts\)/)).toBeInTheDocument();
    expect(screen.getByText('Step 1:')).toBeInTheDocument();
    expect(screen.getByText('Review Linked Transactions')).toBeInTheDocument();
  });

  it('opens action detail modal when Details button is clicked', async () => {
    renderComponent();

    const detailsBtn = await screen.findByRole('button', { name: /Details/i });
    fireEvent.click(detailsBtn);

    expect(await screen.findByText('Why This Action Was Generated')).toBeInTheDocument();
    expect(screen.getByText('Lifecycle History (Append-Only Audit Trail)')).toBeInTheDocument();
    expect(screen.getByText('created')).toBeInTheDocument();
  });

  it('handles Start Action lifecycle transition workflow', async () => {
    renderComponent();

    const startBtn = await screen.findByRole('button', { name: /Start Action/i });
    fireEvent.click(startBtn);

    expect(await screen.findByText('Start Working on Action')).toBeInTheDocument();

    const confirmBtn = screen.getByRole('button', { name: /Confirm/i });
    fireEvent.click(confirmBtn);

    await waitFor(() => {
      expect(financialService.transitionAction).toHaveBeenCalledWith('act-101', {
        status: 'in_progress',
        reason: undefined,
        notes: undefined,
      });
    });
  });

  it('validates mandatory dismissal reason when dismissing an action', async () => {
    renderComponent();

    const dismissBtn = await screen.findByRole('button', { name: /Dismiss/i });
    fireEvent.click(dismissBtn);

    expect(await screen.findByText('Dismiss Recommendation')).toBeInTheDocument();

    // Confirm without typing reason
    const confirmBtn = screen.getByRole('button', { name: /Confirm/i });
    fireEvent.click(confirmBtn);

    // Validation error should show
    expect(await screen.findByText(/A non-empty dismissal reason is required/)).toBeInTheDocument();
    expect(financialService.transitionAction).not.toHaveBeenCalled();

    // Type valid reason
    const textarea = screen.getByPlaceholderText(/Authorized annual software license/i);
    fireEvent.change(textarea, {
      target: { value: 'Legitimate separate batch purchase order #771' },
    });

    fireEvent.click(confirmBtn);

    await waitFor(() => {
      expect(financialService.transitionAction).toHaveBeenCalledWith('act-101', {
        status: 'dismissed',
        reason: 'Legitimate separate batch purchase order #771',
        notes: undefined,
      });
    });
  });

  it('triggers recommendation evaluation when Evaluate Now is clicked', async () => {
    renderComponent();

    const evalBtn = await screen.findByRole('button', { name: /Evaluate Now/i });
    fireEvent.click(evalBtn);

    await waitFor(() => {
      expect(financialService.evaluateActions).toHaveBeenCalled();
    });
  });
});
